"""Generate the arm chain's checked-in ACTIVATION TABLE S(x) (#106 P6b).

Design: docs/octopus_p6_sim_port_design_2026-10-30.md section 6.5 (critique
finding 8). The stiffening wave of an octopus reach (Yekutieli et al. 2005 I/II,
10.1152/jn.00684.2004 / jn.00685.2004) is the sigmoid

    a(s, t) = a_ca * S((s_front(t) - s) / w),      S(x) = (1 + tanh x) / 2

and the kit has no tanh. So S is a TABLE, written offline here (the L° precedent,
tools/gen_light_table.py / cpp/src/light_emission_table.inc), compiled into the
engine (P6c's arm_chain_solver.cpp #includes the .inc) and parsed by the integer
reference (docs/octopus_integer_reference/chain_ref_q.py) from the SAME file.

THE GRID AND THE CURRENCY. 1025 samples of S at x_i = -8 + i / 64, i = 0..1024
(step 1/64 = 2^10 Q16 counts, so the lookup's index is a SHIFT of the Q16
argument), each an int32 in Q16 (65536 = 1.0), round half away from zero.
S(-8) = 1.1e-7 -> 0, S(8) = 1 - 1.1e-7 -> 65536. The sample count is the row's
dial `[creatures.*.solver] activation_table_samples`; the test holds them equal.

THE LOOKUP LAW (the reference's `activation_s_q16`, P6c copies it):

    x  = clamp(x_q16, -8 * 65536, 8 * 65536)
    u  = x + 8 * 65536                  (0 .. 2^20)
    i  = min(u >> 10, 1023);  f = u - (i << 10)      (0 .. 1024)
    S  = T[i] + shr_round_away((T[i+1] - T[i]) * f, 10)

tests/test_activation_table.py re-runs `compute_table()` and requires every
entry within ONE count (a machine's libm tanh may differ in its last ULP).

Run:
    C:/Users/steen/anaconda3/python.exe tools/gen_activation_table.py           # check (exit 1 on drift)
    C:/Users/steen/anaconda3/python.exe tools/gen_activation_table.py --write   # regenerate the .inc
"""
from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INC_PATH = ROOT / "cpp" / "src" / "activation_table.inc"

ACT_X_MAX = 8                 # the grid is x in [-ACT_X_MAX, ACT_X_MAX]
ACT_STEP_SHIFT = 10           # step 1/64 = 2^10 Q16 counts
ACT_Q_SHIFT = 16              # the samples are Q16 (65536 = 1.0)
ACT_INTERVALS = (2 * ACT_X_MAX << 16) >> ACT_STEP_SHIFT     # 1024
ACT_SAMPLES = ACT_INTERVALS + 1                            # 1025
PER_LINE = 8


def compute_table() -> list[int]:
    """The 1025 Q16 samples, round half away from zero (offline float: tanh)."""
    out = []
    for i in range(ACT_SAMPLES):
        x = -ACT_X_MAX + i / float(1 << (16 - ACT_STEP_SHIFT))
        s = 0.5 * (1.0 + math.tanh(x)) * float(1 << ACT_Q_SHIFT)
        out.append(int(math.floor(s + 0.5)))      # s >= 0: half away == half up
    return out


def render_inc(table: list[int]) -> str:
    assert len(table) == ACT_SAMPLES
    out = [
        "// GENERATED by tools/gen_activation_table.py -- DO NOT EDIT BY HAND.",
        "// The arm chain's ACTIVATION TABLE (#106 P6b; design",
        "// docs/octopus_p6_sim_port_design_2026-10-30.md section 6.5): Yekutieli's",
        "// stiffening-wave sigmoid S(x) = (1 + tanh x) / 2 at x_i = -8 + i / 64,",
        "// i = 0 .. 1024, each an int32 in Q16 (65536 = 1.0), round half away from",
        "// zero. Lookup (the reference's activation_s_q16): clamp x_q16 to +-8,",
        "// u = x + 8*65536, i = min(u >> 10, 1023), f = u - (i << 10),",
        "// S = T[i] + shr_round_away((T[i+1] - T[i]) * f, 10).",
        "// Regenerate with `tools/gen_activation_table.py --write`;",
        "// tests/test_activation_table.py fails until you do.",
        f"constexpr int ACT_TABLE_X_MAX = {ACT_X_MAX};",
        f"constexpr int ACT_TABLE_STEP_SHIFT = {ACT_STEP_SHIFT};",
        f"constexpr int ACT_TABLE_SAMPLES = {ACT_SAMPLES};",
        f"constexpr int32_t ACT_TABLE_DATA[{ACT_SAMPLES}] = {{",
    ]
    for s in range(0, ACT_SAMPLES, PER_LINE):
        out.append("    " + ", ".join(str(int(v)) for v in table[s:s + PER_LINE]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def parse_inc(path: Path = INC_PATH) -> dict:
    """The checked-in table: {"x_max", "step_shift", "samples", "data"} -- every
    integer between ACT_TABLE_DATA's braces, in order. The ONE reader the
    integer reference and the tests use."""
    text = Path(path).read_text(encoding="utf-8")
    meta = {}
    for key, name in (("x_max", "ACT_TABLE_X_MAX"), ("step_shift", "ACT_TABLE_STEP_SHIFT"),
                      ("samples", "ACT_TABLE_SAMPLES")):
        m = re.search(name + r"\s*=\s*(\d+)\s*;", text)
        if m is None:
            raise RuntimeError(f"{path}: no {name}")
        meta[key] = int(m.group(1))
    body = text[text.index("{", text.index("ACT_TABLE_DATA")) + 1: text.rindex("}")]
    body = re.sub(r"//[^\n]*", "", body)
    data = [int(v) for v in re.findall(r"-?\d+", body)]
    if len(data) != meta["samples"]:
        raise RuntimeError(f"{path}: {len(data)} entries, header says {meta['samples']}")
    meta["data"] = tuple(data)
    return meta


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true", help="regenerate cpp/src/activation_table.inc")
    args = ap.parse_args(argv)
    table = compute_table()
    if args.write:
        INC_PATH.write_text(render_inc(table), encoding="utf-8", newline="\n")
        print(f"wrote {INC_PATH.relative_to(ROOT)}: {ACT_SAMPLES} samples, "
              f"S(-8) = {table[0]}, S(0) = {table[ACT_INTERVALS // 2]}, S(8) = {table[-1]}")
        return 0
    got = parse_inc()
    diff = max(abs(a - b) for a, b in zip(got["data"], table))
    ok = got["samples"] == ACT_SAMPLES and diff <= 1
    print(f"checked-in table: {got['samples']} samples; max |entry - regenerated| = {diff} "
          f"count(s) -> {'OK' if ok else 'DRIFTED: run --write'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
