"""Where the test suite's time goes -- the measurement instrument of #205.

Reads the output of one suite run made with pytest's durations report

    <breach-py> -m pytest tests -q --durations=0 --durations-min=0.5 > run.txt

and prints the tables of ``docs/test_suite_timing_2026-11-15.md`` (time per
test file, with the file's last commit date, and per kind of test, the kinds
read from each test's source by ``tests/_suite_kinds.py``), or writes the
measured slow list the conftest marks ``slow`` from.

    python tools/suite_timing.py run.txt                    # the tables
    python tools/suite_timing.py run.txt --write-slow       # tests/slow_tests.txt
    python tools/suite_timing.py run.txt --write-slow --threshold 3.0

A test's time is its setup + call + teardown. With ``--durations=200`` (the
2026-11-14 run) only the slowest 200 rows are listed; the rest of the run is
reported as one remainder line.
"""
from __future__ import annotations

import argparse
import collections
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))
import _suite_kinds  # noqa: E402

SLOW_LIST = ROOT / "tests" / "slow_tests.txt"
DEFAULT_THRESHOLD_S = 2.0

_ROW = re.compile(r"\s*([\d.]+)s (setup|call|teardown)\s+(\S+)")
_TOTAL = re.compile(r" in ([\d.]+)s")


def read_run(path: Path) -> tuple[dict[str, float], float | None]:
    """(nodeid -> seconds, the run's wall time) from a pytest output file."""
    text = path.read_bytes().decode("utf-8", errors="replace")
    per: dict[str, float] = collections.defaultdict(float)
    for line in text.splitlines():
        m = _ROW.match(line)
        if m:
            per[m[3]] += float(m[1])
    totals = _TOTAL.findall(text)
    return dict(per), (float(totals[-1]) if totals else None)


def last_change(rel: str) -> str:
    out = subprocess.run(["git", "-C", str(ROOT), "log", "-1", "--format=%cs",
                          "--", rel], capture_output=True, text=True)
    return out.stdout.strip() or "untracked"


def tables(per: dict[str, float], wall: float | None) -> str:
    listed = sum(per.values())
    by_file: dict[str, float] = collections.defaultdict(float)
    n_file: collections.Counter = collections.Counter()
    by_kind: dict[str, float] = collections.defaultdict(float)
    n_kind: collections.Counter = collections.Counter()
    for nodeid, secs in per.items():
        path, name = _suite_kinds.split_nodeid(nodeid)
        by_file[path] += secs
        n_file[path] += 1
        k = _suite_kinds.kind(str(ROOT / path), name)
        by_kind[k] += secs
        n_kind[k] += 1
    lines = []
    if wall:
        lines.append(f"Run: {wall:.0f} s wall; the listed tests {listed:.0f} s "
                     f"({100 * listed / wall:.0f} %), everything else "
                     f"{wall - listed:.0f} s.\n")
    lines += ["| kind | seconds | share | tests listed |", "|---|---:|---:|---:|"]
    for k, s in sorted(by_kind.items(), key=lambda kv: -kv[1]):
        share = f"{100 * s / wall:.0f} %" if wall else ""
        lines.append(f"| {k} | {s:.0f} | {share} | {n_kind[k]} |")
    if wall:
        lines.append(f"| (not listed) | {wall - listed:.0f} | "
                     f"{100 * (wall - listed) / wall:.0f} % | |")
    lines += ["", "| file | seconds | tests listed | last change |",
              "|---|---:|---:|---|"]
    for f, s in sorted(by_file.items(), key=lambda kv: -kv[1]):
        lines.append(f"| `{f}` | {s:.1f} | {n_file[f]} | {last_change(f)} |")
    return "\n".join(lines)


def write_slow(per: dict[str, float], threshold: float, source: Path) -> int:
    rows = sorted(((s, n) for n, s in per.items() if s >= threshold),
                  key=lambda r: (-r[0], r[1]))
    head = [
        "# The measured slow tests (#205): every test whose setup + call +",
        f"# teardown took at least {threshold:g} s in one full suite run.",
        "# GENERATED by tools/suite_timing.py --write-slow from that run's",
        "# --durations output -- regenerate, never hand-edit. The conftest marks",
        "# these `slow`; `pytest tests -q -m \"not slow\"` is the fast tier.",
        f"# source: {source.name}",
        "",
    ]
    SLOW_LIST.write_text("\n".join(head + [f"{s:.2f} {n}" for s, n in rows])
                         + "\n", encoding="utf-8")
    return len(rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Where the test suite's time "
                                 "goes (#205): tables or the slow list.")
    ap.add_argument("run", type=Path, help="pytest output with --durations")
    ap.add_argument("--write-slow", action="store_true")
    ap.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD_S)
    args = ap.parse_args(argv)
    per, wall = read_run(args.run)
    if not per:
        print(f"no durations rows in {args.run}", file=sys.stderr)
        return 1
    if args.write_slow:
        n = write_slow(per, args.threshold, args.run)
        fast = sum(s for s in per.values() if s < args.threshold)
        rest = (wall - sum(per.values())) if wall else 0.0
        print(f"{SLOW_LIST.relative_to(ROOT).as_posix()}: {n} tests at >= "
              f"{args.threshold:g} s; the fast tier measured ~{fast + rest:.0f} s")
        return 0
    print(tables(per, wall))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
