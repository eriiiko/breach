r"""tools/gen_octopus_tank.py -- generates levels/octopus_tank/, the level to
WATCH the simulated octopus in (#106 P7, the render patch's HUMAN-TEST level).

  * one flooded room: a hull box of 66 x 42 tiles at the game's 0.333 m tile
    (22 x 14 m), 2 m of water on every floor tile -- the arm chain's v1
    assumption (water everywhere: ``tests/_creature_scenarios.write_room``'s
    flooded room, the buoyancy the [creatures.octopus] row's g_eff assumes);
  * ONE octopus (``[[creature]]``) at rest in the middle of the room, facing
    the squad (West): its rest pose -- every arm straight and radial, 2.99 m
    from the crown centre -- lies on open floor (the loader's grid door);
    with its grab PROP (#106 P6g, ``prop = true``), so USE grabs something;
  * the squad: three marines (``[[spawn]]``) at the west end, under the human
    control scheme -- the authored single-player path. Without a controller
    the octopus IDLES there (its hub's default: seated arms, two exploring);
  * nine static lamps over the room, warm and bright (2.5), three of them
    close around the octopus, so the animal reads from above;
  * ``match.toml`` for ``main.py --control match``: the same octopus driven by
    the ``creature`` controller, which crawls it at the nearest unit it sees,
    and two one-marine teams standing still (``idle``) in two
    ``[[spawn_room]]``s at the west end. A match needs two teams, each in its
    own spawn room (the match door), so the spawn rooms exist for the MATCH
    only; the single-player path reads ``[[spawn]]`` and never them.

ONE WRITER, LEVEL_LIB ONLY (CLAUDE.md "Level generators"). DETERMINISTIC.

Run:
    C:/Users/steen/anaconda3/python.exe tools/gen_octopus_tank.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
for _p in (ROOT, ROOT / "src", ROOT / "tools"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

import level_lib  # noqa: E402
from level_loader import LightEntry, SpawnEntry  # noqa: E402
from simulation import water_fixed  # noqa: E402
from simulation.match import CreatureSpawn, MatchSpec, MatchTeam, SpawnRoom  # noqa: E402
from simulation.materials import MAT_AIR, MAT_HULL  # noqa: E402

LEVEL_NAME = "octopus_tank"
DEFAULT_OUT_DIR = ROOT / "levels" / LEVEL_NAME
TILE_SIZE_M = 0.333
W, H = 66, 42                     # tiles, hull included
FLOOD_M = 2.0                     # water depth on every floor tile
PX = 16                           # diffuse px per tile

# The octopus: footprint top-left (3x3), facing West (180 deg) toward the squad,
# with its grab PROP beside it (#106 P6g: USE -- keyboard F, gamepad X --
# grabs it; the row's prop_at_m, ahead and to its left).
OCTOPUS = CreatureSpawn("octopus", 41.0, 19.5, heading=180.0, prop=True)
# The squad (single player): 3x3 footprints at the west end.
SQUAD = (("Alpha", 6, 14), ("Bravo", 6, 19), ("Cobra", 6, 24))
LAMPS = ((14.5, 10.5), (33.5, 10.5), (52.5, 10.5),
         (14.5, 31.5), (33.5, 31.5), (52.5, 31.5),
         (42.5, 6.5), (42.5, 35.5), (24.5, 21.5))
LAMP_COLOR = (1.0, 214 / 255, 171 / 255)
LAMP_INTENSITY = 2.5

# The match: two one-marine teams standing still at the west end, the octopus
# hunting them (the default creature controller).
MATCH_ROOMS = (SpawnRoom(team=0, x=3, y=6, w=8, h=8, max_per_team=1),
               SpawnRoom(team=1, x=3, y=28, w=8, h=8, max_per_team=1))
IDLE_TEAM = MatchTeam(n=1, loadout="rifleman", env_profile="default", controller="idle")
MATCH = MatchSpec(teams=(IDLE_TEAM, IDLE_TEAM), seed=106, time_limit_s=300.0,
                  creatures=(OCTOPUS,))

FLOOR = (150, 152, 150)
FLOOR_ALT = (142, 144, 142)
HULL = (70, 74, 84)

HEADER_COMMENTS = (
    "OCTOPUS TANK -- the level to watch the simulated octopus in (#106 P7).",
    "GENERATED by tools/gen_octopus_tank.py through level_lib: a 22 x 14 m",
    "room flooded 2 m deep, one octopus at rest in the middle, three marines",
    "at the west end (single player: the octopus idles), nine lamps;",
    "match.toml: the octopus hunts two idle one-marine teams",
    "(main.py --level octopus_tank --control match).",
    "",
    "v2 codes ARE canon material ids (src/simulation/materials.py):",
    "  0=air 1=hull",
)


def build_tilemap() -> np.ndarray:
    tm = np.full((H, W), MAT_HULL, dtype=np.int32)
    tm[1:H - 1, 1:W - 1] = MAT_AIR
    for (_n, x, y) in SQUAD:
        assert (tm[y:y + 3, x:x + 3] == MAT_AIR).all(), f"{_n} is not on floor"
    return tm


def build_diffuse(tm: np.ndarray) -> Image.Image:
    """Flat light-grey floor tiles with darkened seams (the studios' render
    art), dark hull: the animal reads against it from above."""
    img = np.zeros((H * PX, W * PX, 3), dtype=np.uint8)
    for ty in range(H):
        for tx in range(W):
            if tm[ty, tx] == MAT_AIR:
                c = FLOOR_ALT if (tx + ty) % 2 else FLOOR
            else:
                c = HULL
            img[ty * PX:(ty + 1) * PX, tx * PX:(tx + 1) * PX] = c
    img[::PX, :, :] = (img[::PX, :, :] * 0.82).astype(np.uint8)
    img[:, ::PX, :] = (img[:, ::PX, :] * 0.82).astype(np.uint8)
    return Image.fromarray(img)


def build_water(tm: np.ndarray) -> np.ndarray:
    return np.where(tm == MAT_AIR, water_fixed.quantize_scalar(FLOOD_M), 0).astype(np.int32)


def main(out_dir: Path = DEFAULT_OUT_DIR) -> None:
    out_dir = Path(out_dir)
    for name in ("level.toml", "tilemap.csv", "diffuse.png", "water_init.npy",
                 "match.toml"):
        p = out_dir / name
        if p.exists():
            p.unlink()
    out_dir.mkdir(parents=True, exist_ok=True)

    toml_path = level_lib.write_level_header(
        out_dir, name="Octopus Tank", tile_size_m=TILE_SIZE_M,
        comment_lines=HEADER_COMMENTS)
    tm = build_tilemap()
    level_lib.write_tilemap_csv(out_dir, tm, csv_bak=False)
    build_diffuse(tm).save(out_dir / "diffuse.png")
    level_lib.write_water(out_dir, build_water(tm), npy_bak=False)
    spawns = [SpawnEntry(name=n, team=0, x=x, y=y, footprint=3) for (n, x, y) in SQUAD]
    lights = [LightEntry(x=x, y=y, color=LAMP_COLOR, intensity=LAMP_INTENSITY,
                         range=16.0) for (x, y) in LAMPS]
    level_lib.write_managed_blocks(
        toml_path,
        {"spawn": lambda nl: level_lib.format_spawn_lines(spawns, nl),
         "light": lambda nl: level_lib.format_light_lines(lights, nl)})
    level_lib.write_creatures(toml_path, [OCTOPUS])
    level_lib.write_spawn_rooms(toml_path, list(MATCH_ROOMS))
    level_lib.write_match(out_dir, MATCH)
    print(f"wrote {out_dir}  ({W}x{H} tiles at {TILE_SIZE_M} m, flooded {FLOOD_M} m)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT_DIR)
